def _padded(first: int, window: np.ndarray) -> np.ndarray:
    """The window placed at its own sample indices."""
    return np.concatenate([np.zeros(first), window.astype(np.float32).astype(float)])


def test_a9_3_gives_segmenteds_joins() -> None:
    got = muggeo_segmented(_padded(5957, _A9_3), 5957, 6041, 6086, 16663, 3, 1e-3, False)
    assert got.status == FITTED and (got.first, got.last) == (5957, 6224)
    assert np.allclose(got.psi, (6060.9928568658715, 6063.837632787488), rtol=0, atol=1e-6)
    assert got.idx == 6060


def test_e4_1_gives_segmenteds_joins() -> None:
    got = muggeo_segmented(_padded(3181, _E4_1), 2974, 3301, 3340, 3921, 3, 1e-3, False)
    assert got.status == FITTED and (got.first, got.last) == (3181, 3460)
    assert np.allclose(got.psi, (3307.0003768683014, 3320.6531873306103), rtol=0, atol=1e-6)
    assert got.idx == 3307


def test_g5_1_fails_as_segmented_does_and_restarts_recover_it() -> None:
    f = _padded(1200, _G5_1)
    off = muggeo_segmented(f, 1127, 1314, 1351, 1617, 3, 1e-3, False)
    assert off.idx is None and off.status.startswith(NO_FIT)
    on = muggeo_segmented(f, 1127, 1314, 1351, 1617, 3, 1e-3, True)
    assert on.status.startswith(WARNED) and "outdistanced" in on.status
    assert np.allclose(on.psi, (1329.9999, 1332.0001), rtol=0, atol=1e-6)
    assert on.idx == 1329


