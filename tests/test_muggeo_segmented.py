"""Muggeo's segmented regression, and fit_segments running it.

Three windows from the test ruptures (saved force, float32 as stored) are
fitted at tolerance 1e-3 and compared with the joins Muggeo's R package
segmented 2.2-2 gave on the same windows.
"""

from types import SimpleNamespace

import numpy as np

from smfs_catalog.muggeo_segmented import (
    FITTED, NO_FIT, WARNED, fit_window, muggeo_segmented,
)
from smfs_catalog.roi_events import CurveEvents, ROI, Rupture, Segment, fit_segments
from smfs_catalog.rupture_algorithms import RUPTURE_ALGORITHMS, fit_deflection

LAST_ON_RAMP = 300          # the last sample before the fall
LEFT, RIGHT = 290, 319      # the d1 crossings bracketing it (width 30)


def _ramp(noise: float = 1.0, seed: int = 0) -> np.ndarray:
    """A rising ramp, a 4-sample fall after LAST_ON_RAMP, then a flat level."""
    i = np.arange(400, dtype=float)
    f = 0.5 * i
    top = f[LAST_ON_RAMP]
    for k, frac in enumerate((0.75, 0.5, 0.25, 0.0), start=1):
        f[LAST_ON_RAMP + k] = top * frac
    f[LAST_ON_RAMP + 5:] = 0.0
    return f + np.random.default_rng(seed).normal(0.0, noise, f.size)


def test_the_window_stops_at_the_segment_start_and_the_next_rupture() -> None:
    assert fit_window(0, LEFT, RIGHT, 399, 3) == (200, 399)
    assert fit_window(250, LEFT, RIGHT, 399, 3) == (250, 399)
    assert fit_window(0, LEFT, RIGHT, 330, 3) == (200, 330)
    assert fit_window(0, LEFT, RIGHT, 999, 1) == (260, 349)


def test_the_point_is_the_last_sample_before_the_fall() -> None:
    for restarts in (False, True):
        got = muggeo_segmented(_ramp(), 0, LEFT, RIGHT, 399, 3, 1e-3, restarts)
        assert got.idx == LAST_ON_RAMP and got.status == FITTED
        assert got.first == 200 and got.last == 399


def test_a_rerun_repeats_exactly() -> None:
    f = _ramp(noise=3.0)
    first = muggeo_segmented(f, 0, LEFT, RIGHT, 399, 3, 1e-3, True)
    again = muggeo_segmented(f, 0, LEFT, RIGHT, 399, 3, 1e-3, True)
    assert first == again


def test_the_registry_lists_its_three_settings() -> None:
    algo = RUPTURE_ALGORITHMS["muggeo_segmented"]
    assert algo.settings == ("muggeo_fit_window_multiplier",
                             "muggeo_tolerance_idx", "muggeo_restarts_idx")
    assert algo.raw_signal
    raw, low = np.zeros(3), np.ones(3)
    assert fit_deflection("muggeo_segmented", raw, low) is raw


def _events() -> CurveEvents:
    rup = Rupture(idx=303, piezo_nm=303.0, d1_height=1.0,
                  rise_idx=LEFT, fall_idx=RIGHT)
    seg = Segment(left_idx=0, right_idx=LEFT, left_piezo_nm=0.0,
                  right_piezo_nm=float(LEFT))
    return CurveEvents(detector="test", rois=[ROI(
        onset_idx=0, return_idx=RIGHT, onset_piezo_nm=0.0,
        return_piezo_nm=float(RIGHT), ruptures=[rup], segments=[seg])])


def test_fit_segments_ends_the_segment_at_the_point() -> None:
    raw = _ramp()
    curve = SimpleNamespace(defl_retr=raw, piezo_retr=np.arange(400, dtype=float),
                            spring_constant=1.0, sample_rate_hz=1000.0)
    smooth = np.convolve(raw, np.ones(31) / 31, mode="same")
    events = _events()
    fit_segments(curve, events, 0.0, 1.0, 0.0, low_retr=smooth,
                 rupture_algorithm="muggeo_segmented")
    rup, seg = events.rois[0].ruptures[0], events.rois[0].segments[0]
    assert rup.force_idx == LAST_ON_RAMP and seg.right_idx == LAST_ON_RAMP
    assert rup.force_pN == raw[LAST_ON_RAMP], "the saved signal's value"
    assert rup.point_status == FITTED


def test_no_fit_gives_no_force() -> None:
    curve = SimpleNamespace(defl_retr=_padded(1200, _G5_1),
                            piezo_retr=np.arange(1466, dtype=float),
                            spring_constant=1.0, sample_rate_hz=1000.0)
    rup = Rupture(idx=1330, piezo_nm=1330.0, d1_height=1.0,
                  rise_idx=1314, fall_idx=1351)
    seg = Segment(left_idx=1127, right_idx=1314, left_piezo_nm=1127.0,
                  right_piezo_nm=1314.0)
    events = CurveEvents(detector="test", rois=[ROI(
        onset_idx=1127, return_idx=1351, onset_piezo_nm=1127.0,
        return_piezo_nm=1351.0, ruptures=[rup], segments=[seg])])
    fit_segments(curve, events, 0.0, 1.0, 0.0, low_retr=curve.defl_retr,
                 rupture_algorithm="muggeo_segmented", muggeo_restarts=False)
    assert rup.point_status.startswith(NO_FIT)
    assert rup.force_pN is None
    assert seg.fit_status == "no_fit" and seg.fit_detail == "no force peak"


